!> Unit tests for the XC table I/O module
!!
!! These tests are self-contained: every table they read is generated by the
!! test itself in a scratch directory under build/ and removed afterwards.
!!
!! Rationale: generated fixtures keep the I/O tests meaningful without requiring
!! a checked-in table directory.
program test_table_io
    use fortuno_serial, only: execute_serial_cmd_app, check_failed => serial_check_failed
    implicit none

    call execute_serial_cmd_app(get_table_io_tests())

contains

    function get_table_io_tests() result(tests)
        use fortuno_serial, only: test_list, test => serial_case_item
        type(test_list) :: tests

        tests = test_list([ &
            test("read_cpp_u4", test_read_cpp_u4), &
            test("extract_u_standard", test_extract_u_standard), &
            test("extract_u_binary", test_extract_u_binary), &
            test("extract_u_invalid", test_extract_u_invalid), &
            test("table_filename_roundtrip", test_table_filename_roundtrip), &
            test("binary_roundtrip", test_binary_roundtrip), &
            test("table_dimensions", test_table_dimensions), &
            test("table_ranges", test_table_ranges), &
            test("missing_file", test_missing_file), &
            test("missing_file_roundtrip_is_safe", test_missing_file_roundtrip_is_safe), &
            test("deallocate_table", test_deallocate_table), &
            test("multiple_tables", test_multiple_tables), &
            test("write_rejects_nonfinite", test_write_rejects_nonfinite) &
        ])
    end function get_table_io_tests

    ! write_fortran_table must refuse a table with a NaN or an Inf anywhere in
    ! exc/vxc_up/vxc_down: no file, ERROR_NOT_A_NUMBER. Each array is probed
    ! separately, with +Inf, -Inf and NaN, so that a check on ieee_is_nan alone
    ! (which lets ±Inf through) fails this test.
    subroutine test_write_rejects_nonfinite()
        use fortuno_serial, only: check => serial_check
        use table_io
        use lsda_constants, only: dp
        use lsda_errors, only: ERROR_NOT_A_NUMBER, ERROR_SUCCESS
        use, intrinsic :: ieee_arithmetic, only: ieee_value, ieee_quiet_nan, &
            ieee_positive_inf, ieee_negative_inf

        character(len=*), parameter :: bin_file = "build/test_tmp/nonfinite_table_u4.00.dat"
        type(xc_table_t) :: table
        real(dp) :: bad(3)
        integer :: status, n_exc, n_up, n_dn, which_array, which_value
        logical :: exists

        bad(1) = ieee_value(0.0_dp, ieee_quiet_nan)
        bad(2) = ieee_value(0.0_dp, ieee_positive_inf)
        bad(3) = ieee_value(0.0_dp, ieee_negative_inf)

        call ensure_scratch_dir()
        call remove_file(bin_file)

        do which_array = 1, 3
            do which_value = 1, 3
                call make_finite_table(table)
                select case (which_array)
                case (1); table%exc(2, 2)      = bad(which_value)
                case (2); table%vxc_up(1, 3)   = bad(which_value)
                case (3); table%vxc_down(3, 1) = bad(which_value)
                end select

                call count_nonfinite_entries(table, n_exc, n_up, n_dn)
                call check(n_exc + n_up + n_dn == 1, &
                    "exactly one non-finite entry should be counted")
                call check(merge(n_exc, merge(n_up, n_dn, which_array == 2), which_array == 1) == 1, &
                    "the non-finite entry should be attributed to the right array")

                call write_fortran_table(bin_file, table, status)
                call check(status == ERROR_NOT_A_NUMBER, &
                    "write_fortran_table must return ERROR_NOT_A_NUMBER for a non-finite table")
                inquire(file=bin_file, exist=exists)
                call check(.not. exists, "no file may be created for a non-finite table")

                call deallocate_table(table)
                call remove_file(bin_file)
            end do
        end do

        ! Control: the same table with every entry finite is written.
        call make_finite_table(table)
        call count_nonfinite_entries(table, n_exc, n_up, n_dn)
        call check(n_exc + n_up + n_dn == 0, "a finite table has no non-finite entries")
        call write_fortran_table(bin_file, table, status)
        call check(status == ERROR_SUCCESS, "a finite table must be written")
        inquire(file=bin_file, exist=exists)
        call check(exists, "the finite table file must exist")
        call deallocate_table(table)
        call remove_file(bin_file)
    end subroutine test_write_rejects_nonfinite

    ! A tiny 3x3 table with arbitrary finite values.
    subroutine make_finite_table(table)
        use table_io, only: xc_table_t
        use lsda_constants, only: dp
        type(xc_table_t), intent(out) :: table
        integer :: i, j

        table%U = 4.0_dp
        table%n_points_n = 3
        table%n_points_m = 3
        allocate(table%n_grid(3), table%m_grid(3, 3))
        allocate(table%exc(3, 3), table%vxc_up(3, 3), table%vxc_down(3, 3))
        do i = 1, 3
            table%n_grid(i) = 0.25_dp * real(i, dp)
            do j = 1, 3
                table%m_grid(j, i) = table%n_grid(i) * real(j - 2, dp)
                table%exc(j, i) = -0.1_dp * real(i + j, dp)
                table%vxc_up(j, i) = 0.01_dp * real(i - j, dp)
                table%vxc_down(j, i) = 0.02_dp * real(j - i, dp)
            end do
        end do
    end subroutine make_finite_table


    ! ------------------------------------------------------------------
    ! Fixture helpers
    ! ------------------------------------------------------------------

    !> Number of density blocks written by make_cpp_table_file
    integer function n_blocks_ref()
        n_blocks_ref = 50
    end function n_blocks_ref

    !> Number of magnetization rows per block written by make_cpp_table_file
    integer function n_mag_ref()
        n_mag_ref = 101
    end function n_mag_ref

    !> Reference density of block i: 0.02, 0.04, ... 1.00
    function n_ref(i) result(n_val)
        use lsda_constants, only: dp
        integer, intent(in) :: i
        real(dp) :: n_val
        n_val = real(i, dp) / real(n_blocks_ref(), dp)
    end function n_ref

    !> Reference magnetization of row j in block i: uniform grid on [0, n]
    function m_ref(j, i) result(m_val)
        use lsda_constants, only: dp
        integer, intent(in) :: j, i
        real(dp) :: m_val
        m_val = n_ref(i) * real(j - 1, dp) / real(n_mag_ref() - 1, dp)
    end function m_ref

    !> Reference XC energy: strictly negative, as a real XC table must be
    function exc_ref(j, i) result(e_val)
        use lsda_constants, only: dp
        integer, intent(in) :: j, i
        real(dp) :: e_val
        e_val = -0.5_dp * n_ref(i) * (1.0_dp - 0.25_dp * m_ref(j, i)**2)
    end function exc_ref

    !> Reference spin-up XC potential (equals vxc_down at m = 0)
    function vxc_up_ref(j, i) result(v_val)
        use lsda_constants, only: dp
        integer, intent(in) :: j, i
        real(dp) :: v_val
        v_val = -0.5_dp + 0.1_dp * n_ref(i) + 0.05_dp * m_ref(j, i)
    end function vxc_up_ref

    !> Reference spin-down XC potential (equals vxc_up at m = 0)
    function vxc_down_ref(j, i) result(v_val)
        use lsda_constants, only: dp
        integer, intent(in) :: j, i
        real(dp) :: v_val
        v_val = -0.5_dp + 0.1_dp * n_ref(i) - 0.05_dp * m_ref(j, i)
    end function vxc_down_ref

    !> Create the scratch directory used for generated fixtures
    subroutine ensure_scratch_dir()
        call execute_command_line("mkdir -p build/test_tmp")
    end subroutine ensure_scratch_dir

    !> Write a table in the legacy C++ ASCII format
    !!
    !! Layout (as consumed by read_cpp_table):
    !!   n: <density>
    !!   #mag   exc   vxc_up   vxc_down
    !!   <m> <exc> <vxc_up> <vxc_down>      (n_mag_ref() rows)
    !!   ... repeated for n_blocks_ref() densities
    !!
    !! @param[in]  filename Destination path
    !! @param[out] ok       .true. if the file was written successfully
    subroutine make_cpp_table_file(filename, ok)
        character(len=*), intent(in) :: filename
        logical, intent(out) :: ok
        integer :: unit, io_stat, i, j

        call ensure_scratch_dir()

        open(newunit=unit, file=filename, status='replace', action='write', &
             iostat=io_stat)
        if (io_stat /= 0) then
            ok = .false.
            return
        end if

        do i = 1, n_blocks_ref()
            write(unit, '(A,ES24.15)') 'n: ', n_ref(i)
            write(unit, '(A)') '#mag                    exc                     ' // &
                               'vxc_up                  vxc_down'
            do j = 1, n_mag_ref()
                write(unit, '(4ES24.15)') m_ref(j, i), exc_ref(j, i), &
                                          vxc_up_ref(j, i), vxc_down_ref(j, i)
            end do
        end do

        close(unit)
        ok = .true.
    end subroutine make_cpp_table_file

    !> Remove a file created by the tests (no-op if it does not exist)
    subroutine remove_file(filename)
        character(len=*), intent(in) :: filename
        integer :: unit, io_stat

        open(newunit=unit, file=filename, status='old', iostat=io_stat)
        if (io_stat == 0) close(unit, status='delete')
    end subroutine remove_file

    !> Return whether every allocatable table component is available
    logical function table_is_allocated(table)
        use table_io, only: xc_table_t
        type(xc_table_t), intent(in) :: table

        table_is_allocated = allocated(table%n_grid) .and. allocated(table%m_grid) .and. &
                             allocated(table%exc) .and. allocated(table%vxc_up) .and. &
                             allocated(table%vxc_down)
    end function table_is_allocated


    ! ------------------------------------------------------------------
    ! Tests
    ! ------------------------------------------------------------------

    subroutine test_read_cpp_u4()
        use fortuno_serial, only: check => serial_check
        use table_io
        use lsda_constants, only: dp

        type(xc_table_t) :: table
        integer :: status
        logical :: ok
        character(len=*), parameter :: fname = "build/test_tmp/lsda_hub_u4.00"

        call make_cpp_table_file(fname, ok)
        call check(ok, "Fixture table should be written")
        if (check_failed()) then
            call remove_file(fname)
            return
        end if

        call read_cpp_table(fname, table, status)

        call check(status == 0, "Read status should be 0")
        if (check_failed()) then
            call deallocate_table(table)
            call remove_file(fname)
            return
        end if

        call check(abs(table%U - 4.0_dp) < 1.0e-10_dp, "U should be 4.0")
        call check(table%n_points_n == n_blocks_ref(), "Should have 50 density points")
        call check(table%n_points_m == n_mag_ref(), "Should have 101 magnetization points")
        call check(allocated(table%n_grid), "n_grid should be allocated")
        call check(allocated(table%m_grid), "m_grid should be allocated")
        call check(allocated(table%exc), "exc should be allocated")
        call check(allocated(table%vxc_up), "vxc_up should be allocated")
        call check(allocated(table%vxc_down), "vxc_down should be allocated")
        if (check_failed()) then
            call deallocate_table(table)
            call remove_file(fname)
            return
        end if

        ! The parsed values must reproduce what was written
        call check(abs(table%n_grid(1) - n_ref(1)) < 1.0e-10_dp, &
                   "First density should round-trip through the ASCII parser")
        call check(abs(table%n_grid(n_blocks_ref()) - n_ref(n_blocks_ref())) < 1.0e-10_dp, &
                   "Last density should round-trip through the ASCII parser")
        call check(abs(table%exc(7, 13) - exc_ref(7, 13)) < 1.0e-10_dp, &
                   "exc should be parsed into the (mag, density) slot it was written to")
        call check(abs(table%vxc_down(7, 13) - vxc_down_ref(7, 13)) < 1.0e-10_dp, &
                   "vxc_down should be parsed into the correct column")

        call deallocate_table(table)
        call remove_file(fname)
    end subroutine test_read_cpp_u4


