        call check(size(table%m_grid, 2) == table%n_points_n, &
                   "m_grid second dimension should match n_points_n")
        call check(size(table%exc, 1) == table%n_points_m, &
                   "exc first dimension should match n_points_m")
        call check(size(table%exc, 2) == table%n_points_n, &
                   "exc second dimension should match n_points_n")
        call check(size(table%vxc_up, 1) == table%n_points_m .and. &
                   size(table%vxc_up, 2) == table%n_points_n, &
                   "vxc_up dimensions should match the table size")
        call check(size(table%vxc_down, 1) == table%n_points_m .and. &
                   size(table%vxc_down, 2) == table%n_points_n, &
                   "vxc_down dimensions should match the table size")

        call deallocate_table(table)
        call remove_file(fname)
    end subroutine test_table_dimensions


    subroutine test_table_ranges()
        use fortuno_serial, only: check => serial_check
        use table_io
        use lsda_constants, only: dp

        type(xc_table_t) :: table
        integer :: status
        logical :: ok
        real(dp) :: n_min, n_max, m_min, m_max
        character(len=*), parameter :: fname = "build/test_tmp/ranges_hub_u4.00"

        call make_cpp_table_file(fname, ok)
        call check(ok, "Fixture table should be written")
        if (check_failed()) then
            call remove_file(fname)
            return
        end if

        call read_cpp_table(fname, table, status)
        call check(status == 0, "Should read table")
        call check(table_is_allocated(table), "Table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table)
            call remove_file(fname)
            return
        end if

        n_min = minval(table%n_grid)
        n_max = maxval(table%n_grid)

        call check(n_min > 0.0_dp, "Minimum density should be positive")
        call check(n_max <= 1.0_dp + 1.0e-6_dp, "Maximum density should be <= 1")
        call check(n_min < n_max, "Density should be increasing")

        m_min = minval(table%m_grid)
        m_max = maxval(table%m_grid)

        call check(m_min >= 0.0_dp - 1.0e-10_dp, "Minimum magnetization should be >= 0")
        call check(m_max <= n_max + 1.0e-6_dp, "Maximum magnetization should be <= n_max")

        call check(maxval(table%exc) <= 0.0_dp + 1.0e-10_dp, &
                   "XC energy should be negative or zero")

        call check(abs(table%vxc_up(1,1) - table%vxc_down(1,1)) < 1.0e-10_dp, &
                   "At m=0, vxc_up should equal vxc_down")

        call deallocate_table(table)
        call remove_file(fname)
    end subroutine test_table_ranges


    subroutine test_missing_file()
        use fortuno_serial, only: check => serial_check
        use table_io

        type(xc_table_t) :: table
        integer :: status

        call read_cpp_table("build/test_tmp/nonexistent_hub_u4.00", table, status)

        call check(status /= 0, "Should fail for missing file")
        call check(.not. allocated(table%n_grid), "Arrays should not be allocated on error")
        call check(.not. allocated(table%m_grid), "m_grid should not be allocated on error")
        call check(.not. allocated(table%exc), "exc should not be allocated on error")
    end subroutine test_missing_file


    !> A failed read must not leave a table that later writes can choke on
    !!
    !! Regression guard: when the source table is missing, read_cpp_table
    !! returns a non-zero status and an unallocated table. write_fortran_table
    !! must reject that table via its status instead of dereferencing the
    !! unallocated components, and read_fortran_table must report the missing
    !! output file rather than reading stale data.
    subroutine test_missing_file_roundtrip_is_safe()
        use fortuno_serial, only: check => serial_check
        use table_io

        type(xc_table_t) :: table_in, table_out
        integer :: status
        character(len=*), parameter :: bin_file = "build/test_tmp/never_written_u4.00.dat"

        call ensure_scratch_dir()
        call remove_file(bin_file)

        call read_cpp_table("build/test_tmp/nonexistent_hub_u4.00", table_in, status)
        call check(status /= 0, "Reading a missing source table should fail")
        call check(.not. allocated(table_in%n_grid), "Failed read should leave table unallocated")
        if (check_failed()) then
            call deallocate_table(table_in)
            call remove_file(bin_file)
            return
        end if

        call write_fortran_table(bin_file, table_in, status)
        call check(status /= 0, "Writing an unallocated table should fail, not crash")
        if (check_failed()) then
            call deallocate_table(table_in)
            call remove_file(bin_file)
            return
        end if

        call read_fortran_table(bin_file, table_out, status)
        call check(status /= 0, "Reading the never-written binary table should fail")
        call check(.not. allocated(table_out%n_grid), &
                   "Failed binary read should leave table unallocated")
    end subroutine test_missing_file_roundtrip_is_safe


    subroutine test_deallocate_table()
        use fortuno_serial, only: check => serial_check
        use table_io

        type(xc_table_t) :: table
        integer :: status
        logical :: ok
        character(len=*), parameter :: fname = "build/test_tmp/dealloc_hub_u4.00"

        call make_cpp_table_file(fname, ok)
        call check(ok, "Fixture table should be written")
        if (check_failed()) then
            call remove_file(fname)
            return
        end if

        call read_cpp_table(fname, table, status)
        call check(status == 0, "Should read table")
        call check(allocated(table%n_grid), "Arrays should be allocated")
        call check(table_is_allocated(table), "All table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table)
            call remove_file(fname)
            return
        end if

        call deallocate_table(table)

        call check(.not. allocated(table%n_grid), "n_grid should be deallocated")
        call check(.not. allocated(table%m_grid), "m_grid should be deallocated")
        call check(.not. allocated(table%exc), "exc should be deallocated")
        call check(.not. allocated(table%vxc_up), "vxc_up should be deallocated")
        call check(.not. allocated(table%vxc_down), "vxc_down should be deallocated")

        ! Deallocating twice must be a no-op, not an error
        call deallocate_table(table)
        call check(.not. allocated(table%n_grid), "Second deallocate should stay deallocated")

        call remove_file(fname)
    end subroutine test_deallocate_table


    subroutine test_multiple_tables()
        use fortuno_serial, only: check => serial_check
        use table_io
        use lsda_constants, only: dp

        type(xc_table_t) :: table1, table2, table3
        integer :: status
        logical :: ok1, ok2, ok3
        character(len=*), parameter :: f1 = "build/test_tmp/multi_hub_u2.00"
        character(len=*), parameter :: f2 = "build/test_tmp/multi_hub_u4.00"
        character(len=*), parameter :: f3 = "build/test_tmp/multi_hub_u10.00"

        call make_cpp_table_file(f1, ok1)
        call make_cpp_table_file(f2, ok2)
        call make_cpp_table_file(f3, ok3)
        call check(ok1 .and. ok2 .and. ok3, "Fixture tables should be written")
        if (check_failed()) then
            call remove_file(f1)
            call remove_file(f2)
            call remove_file(f3)
            return
        end if

        call read_cpp_table(f1, table1, status)
        call check(status == 0, "Should read U=2 table")
        call check(table_is_allocated(table1), "U=2 table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table1)
            call deallocate_table(table2)
            call deallocate_table(table3)
            call remove_file(f1)
            call remove_file(f2)
            call remove_file(f3)
            return
        end if

        call read_cpp_table(f2, table2, status)
        call check(status == 0, "Should read U=4 table")
        call check(table_is_allocated(table2), "U=4 table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table1)
            call deallocate_table(table2)
            call deallocate_table(table3)
            call remove_file(f1)
            call remove_file(f2)
            call remove_file(f3)
            return
        end if

        call read_cpp_table(f3, table3, status)
        call check(status == 0, "Should read U=10 table")
        call check(table_is_allocated(table3), "U=10 table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table1)
            call deallocate_table(table2)
            call deallocate_table(table3)
            call remove_file(f1)
            call remove_file(f2)
            call remove_file(f3)
            return
        end if

        ! Each table must carry the U encoded in its own filename: tables held
        ! simultaneously must not share state.
        call check(abs(table1%U - 2.0_dp) < 1.0e-10_dp, "table1 U should be 2.0")
        call check(abs(table2%U - 4.0_dp) < 1.0e-10_dp, "table2 U should be 4.0")
        call check(abs(table3%U - 10.0_dp) < 1.0e-10_dp, "table3 U should be 10.0")

        call check(table1%n_points_n == n_blocks_ref(), "table1 should have 50 density points")
        call check(table2%n_points_n == n_blocks_ref(), "table2 should have 50 density points")
        call check(table3%n_points_n == n_blocks_ref(), "table3 should have 50 density points")

        call check(table1%n_points_m == n_mag_ref(), "table1 should have 101 magnetization points")
        call check(table2%n_points_m == n_mag_ref(), "table2 should have 101 magnetization points")
        call check(table3%n_points_m == n_mag_ref(), "table3 should have 101 magnetization points")

        call deallocate_table(table1)
        call deallocate_table(table2)
        call deallocate_table(table3)
        call remove_file(f1)
        call remove_file(f2)
        call remove_file(f3)
    end subroutine test_multiple_tables

end program test_table_io
