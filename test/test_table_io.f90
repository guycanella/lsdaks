    !> The name the generator writes must be the name the SCF looks up.
    !!
    !! Regression test for the `|U| < 1` divergence: the generator formatted the
    !! magnitude with a bare `F0.2`, which gfortran prints without the leading
    !! zero, so it wrote `xc_table_u.50.dat` while the run-time lookup asked for
    !! `xc_table_u0.50.dat` and never found it - for the whole `0.5 <= |U| < 1`
    !! range.  Both sides now call `xc_table_filename`, so the check is that the
    !! shared name carries the zero and survives `extract_U_from_filename`.
    subroutine test_table_filename_roundtrip()
        use fortuno_serial, only: check => serial_check
        use table_io, only: xc_table_filename, extract_U_from_filename
        use lsda_constants, only: dp

        real(dp), parameter :: U_VALUES(5) = &
            [0.50_dp, 0.75_dp, -0.50_dp, 1.00_dp, 10.00_dp]
        character(len=256) :: path
        real(dp) :: U_back
        integer :: i, status

        do i = 1, size(U_VALUES)
            call xc_table_filename('tables', U_VALUES(i), path)
            call check(index(path, 'xc_table_u.') == 0, &
                       "the table name must never drop the leading zero of |U| < 1")
            call extract_U_from_filename(trim(path), U_back, status)
            call check(status == 0, "the generated table name must be parseable")
            call check(abs(U_back - abs(U_VALUES(i))) < 1.0e-10_dp, &
                       "the table name must round-trip to |U|")
        end do

        call xc_table_filename('tables', 0.5_dp, path)
        call check(trim(path) == 'tables/xc_table_u0.50.dat', &
                   "U = 0.5 must map to xc_table_u0.50.dat")
        call xc_table_filename('dir/', 0.5_dp, path)
        call check(trim(path) == 'dir/xc_table_u0.50.dat', &
                   "a trailing slash must not be doubled")
        call xc_table_filename('', 4.0_dp, path)
        call check(trim(path) == 'xc_table_u4.00.dat', &
                   "an empty directory must give a bare file name")
    end subroutine test_table_filename_roundtrip


    subroutine test_binary_roundtrip()
        use fortuno_serial, only: check => serial_check
        use table_io
        use lsda_constants, only: dp

        type(xc_table_t) :: table_in, table_out
        integer :: status
        logical :: ok
        character(len=*), parameter :: src_file = "build/test_tmp/roundtrip_hub_u4.00"
        character(len=*), parameter :: bin_file = "build/test_tmp/roundtrip_table_u4.00.dat"

        call make_cpp_table_file(src_file, ok)
        call check(ok, "Fixture table should be written")
        if (check_failed()) then
            call remove_file(src_file)
            call remove_file(bin_file)
            return
        end if

        call read_cpp_table(src_file, table_in, status)
        call check(status == 0, "Should read C++ table")
        call check(table_is_allocated(table_in), "C++ table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table_in)
            call remove_file(src_file)
            call remove_file(bin_file)
            return
        end if

        call write_fortran_table(bin_file, table_in, status)
        call check(status == 0, "Should write binary table")
        if (check_failed()) then
            call deallocate_table(table_in)
            call remove_file(src_file)
            call remove_file(bin_file)
            return
        end if

        call read_fortran_table(bin_file, table_out, status)
        call check(status == 0, "Should read binary table")
        call check(table_is_allocated(table_out), "Binary table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table_in)
            call deallocate_table(table_out)
            call remove_file(src_file)
            call remove_file(bin_file)
            return
        end if

        call check(abs(table_in%U - table_out%U) < 1.0e-14_dp, &
                   "U should match after round-trip")
        call check(table_in%n_points_n == table_out%n_points_n, &
                   "n_points_n should match")
        call check(table_in%n_points_m == table_out%n_points_m, &
                   "n_points_m should match")

        ! The binary format is unformatted stream, so the round-trip must hold
        ! over the WHOLE arrays, not just at a couple of sampled indices.
        call check(maxval(abs(table_in%n_grid - table_out%n_grid)) < 1.0e-14_dp, &
                   "n_grid should survive the round-trip to 1e-14")
        call check(maxval(abs(table_in%m_grid - table_out%m_grid)) < 1.0e-14_dp, &
                   "m_grid should survive the round-trip to 1e-14")
        call check(maxval(abs(table_in%exc - table_out%exc)) < 1.0e-14_dp, &
                   "exc should survive the round-trip to 1e-14")
        call check(maxval(abs(table_in%vxc_up - table_out%vxc_up)) < 1.0e-14_dp, &
                   "vxc_up should survive the round-trip to 1e-14")
        call check(maxval(abs(table_in%vxc_down - table_out%vxc_down)) < 1.0e-14_dp, &
                   "vxc_down should survive the round-trip to 1e-14")

        call deallocate_table(table_in)
        call deallocate_table(table_out)
        call remove_file(src_file)
        call remove_file(bin_file)
    end subroutine test_binary_roundtrip


    subroutine test_table_dimensions()
        use fortuno_serial, only: check => serial_check
        use table_io

        type(xc_table_t) :: table
        integer :: status
        logical :: ok
        character(len=*), parameter :: fname = "build/test_tmp/dims_hub_u4.00"

        call make_cpp_table_file(fname, ok)
        call check(ok, "Fixture table should be written")
        if (check_failed()) then
            call remove_file(fname)
            return
        end if

        call read_cpp_table(fname, table, status)
        call check(status == 0, "Should read table")
        call check(table_is_allocated(table), "Table arrays should be allocated")
        if (check_failed()) then
            call deallocate_table(table)
            call remove_file(fname)
            return
        end if

        call check(size(table%n_grid) == table%n_points_n, &
